function compress(str) {
  const wordsArray = str.split(" ");
  const compressedWordsArray = [];

  for (const word of wordsArray) {
    const indexOfFoundWord = compressedWordsArray.findIndex(w => w === word);

    compressedWordsArray.push(indexOfFoundWord === -1 ? word : indexOfFoundWord + 1);
  }

  return compressedWordsArray.join(" ");
}

